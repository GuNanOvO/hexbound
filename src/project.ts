import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import { z } from 'zod';
import { defaultPolicy, loadPolicy, POLICY_FILE, REQUIRED_COMPILER_OPTIONS, STRICT_OPTIONS } from './policy.js';
import { APPLICATION_SOURCE_DIRECTORIES, isAuxiliarySourcePath, isExcludedSourcePath, isToolingJavaScript, rootJavaScriptCommands } from './sources.js';
import type { AnalysisContext, Policy } from './types.js';

const manifestSchema = z.object({
  name: z.string().optional(), workspaces: z.unknown().optional(),
  dependencies: z.record(z.string(), z.string()).optional(), devDependencies: z.record(z.string(), z.string()).optional(),
  scripts: z.record(z.string(), z.string()).optional(),
}).passthrough();
const LOCK_FILES = ['package-lock.json', 'pnpm-lock.yaml', 'yarn.lock', 'bun.lock', 'bun.lockb'];
export const ESLINT_FILES = ['eslint.config.js', 'eslint.config.mjs', 'eslint.config.cjs', 'eslint.config.ts', 'eslint.config.mts', 'eslint.config.cts', '.eslintrc', '.eslintrc.json', '.eslintrc.js', '.eslintrc.cjs'];
const INTEGRATION = "// Generated by Hexbound. Keep the complete restrictive configuration.\nimport { createConfig } from 'hexbound/eslint';\nexport default createConfig(import.meta.dirname);\n";
const INITIALIZATION_TARGETS = ['package.json', 'tsconfig.json', POLICY_FILE, 'AGENTS.md', ...ESLINT_FILES] as const;

function assertRegularDestination(filename: string): void {
  const stat = fs.lstatSync(filename, { throwIfNoEntry: false });
  if (stat && !stat.isFile()) throw new Error(`Refusing to initialize through a non-regular path: ${filename}`);
}
function preflightDestinations(filenames: Iterable<string>): void { for (const filename of filenames) assertRegularDestination(filename); }

function installedVersion(root: string, name: string): string {
  const filename = path.join(root, 'node_modules', name, 'package.json');
  if (!fs.existsSync(filename)) throw new Error(`Missing local ${name}; install project dependencies before running Hexbound`);
  return z.object({ version: z.string() }).parse(JSON.parse(fs.readFileSync(filename, 'utf8'))).version;
}
function major(value: string): number { return Number(value.split('.')[0]); }

export function inspectProject(rootInput: string) {
  const root = fs.realpathSync(path.resolve(rootInput));
  const manifest = manifestSchema.parse(JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')));
  if (manifest.workspaces !== undefined) throw new Error('Workspace/multi-application projects are not supported by this profile');
  const locks = LOCK_FILES.filter(file => fs.existsSync(path.join(root, file)));
  if (locks.length !== 1) throw new Error(`Expected one package-manager lockfile, found ${locks.length}`);
  const apps = ['app', 'src/app'].filter(file => fs.statSync(path.join(root, file), { throwIfNoEntry: false })?.isDirectory());
  if (apps.length !== 1) throw new Error('Expected exactly one App Router tree: app/ or src/app/');
  if (fs.existsSync(path.join(root, 'pages')) || fs.existsSync(path.join(root, 'src/pages'))) throw new Error('Pages Router/hybrid applications are not supported by this profile');
  const versions = { next: installedVersion(root, 'next'), react: installedVersion(root, 'react'), typescript: installedVersion(root, 'typescript'), eslint: installedVersion(root, 'eslint') };
  if (major(versions.next) !== 16 || major(versions.react) !== 19 || versions.typescript !== '6.0.3' || major(versions.eslint) !== 9) {
    throw new Error(`Unsupported version matrix ${JSON.stringify(versions)}; requires Next 16, React 19, TypeScript 6.0.3 and ESLint 9`);
  }
  const declared = { ...manifest.dependencies, ...manifest.devDependencies };
  for (const name of ['next', 'react', 'typescript', 'eslint']) if (!declared[name]) throw new Error(`Declare ${name} in this application's package.json`);
  const app = apps[0]; const lock = locks[0];
  if (!app || !lock) throw new Error('Project admission failed');
  return { root, manifest, versions, app, lock };
}

export function discoverSources(root: string, policy: Policy): { sources: string[]; excluded: string[]; configSources: string[] } {
  const sources: string[] = []; const excluded: string[] = []; const configSources: string[] = [];
  const manifestPath = path.join(root, 'package.json');
  const manifest = fs.existsSync(manifestPath) ? manifestSchema.parse(JSON.parse(fs.readFileSync(manifestPath, 'utf8'))) : undefined;
  const commands = rootJavaScriptCommands(manifest?.scripts ?? {});
  function visit(directory: string): void {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
      const absolute = path.join(directory, entry.name);
      const relative = path.relative(root, absolute).split(path.sep).join('/');
      if (entry.isSymbolicLink()) {
        if (entry.name === 'node_modules') { excluded.push(relative + '/'); continue; }
        throw new Error(`Source symlinks are not supported: ${relative}`);
      }
      if (entry.isDirectory()) {
        if (isExcludedSourcePath(policy, relative) || isAuxiliarySourcePath(root, relative)) { excluded.push(relative + '/'); continue; }
        visit(absolute); continue;
      }
      if (!entry.isFile()) continue;
      if (isExcludedSourcePath(policy, relative)) { excluded.push(relative); continue; }
      if (/\.(?:ts|tsx|mts|cts)$/.test(entry.name)) sources.push(absolute);
      else if (/\.(?:js|jsx|mjs|cjs)$/.test(entry.name)) {
        if (isToolingJavaScript(relative, commands)) {
          excluded.push(relative);
          if (/\.config\.(?:js|mjs|cjs)$/.test(relative)) configSources.push(absolute);
        } else throw new Error(`JavaScript application source is not supported: ${relative}; use TypeScript`);
      }
    }
  }
  visit(root);
  if (!sources.length) throw new Error('Zero source coverage: no owned TypeScript files were found');
  return { sources: sources.sort(), excluded: excluded.sort(), configSources };
}

export function createProjectContext(root: string, policy: Policy, enforce = true): { context: AnalysisContext; excluded: string[]; compilerErrors: string[] } {
  const configFile = path.join(root, 'tsconfig.json');
  const config = ts.readConfigFile(configFile, ts.sys.readFile);
  if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root, undefined, configFile);
  if (parsed.projectReferences?.length) throw new Error('tsconfig references are not supported by this single-app profile');
  if (parsed.errors.length) throw new Error(ts.formatDiagnosticsWithColorAndContext(parsed.errors, { getCanonicalFileName: file => file, getCurrentDirectory: () => root, getNewLine: () => '\n' }));
  if (enforce) {
    for (const option of REQUIRED_COMPILER_OPTIONS) if (parsed.options[option] !== true) throw new Error(`Required compiler option ${option} must be true`);
    for (const option of STRICT_OPTIONS) if (parsed.options[option] === false) throw new Error(`Strict compiler option ${option} cannot be false`);
  }
  const discovered = discoverSources(root, policy);
  const applicationRootNames = discovered.sources.filter(filename => {
    const relative = path.relative(root, filename).split(path.sep).join('/');
    return Object.hasOwn(APPLICATION_SOURCE_DIRECTORIES, relative.split('/')[0] ?? '');
  });
  const rootNames = [...new Set([
    ...parsed.fileNames.filter(filename => {
      const relative = path.relative(root, filename).split(path.sep).join('/');
      return relative === 'next-env.d.ts' || (/\.[cm]?tsx?$/.test(relative) && !isExcludedSourcePath(policy, relative) && !isAuxiliarySourcePath(root, relative));
    }),
    ...applicationRootNames,
  ])];
  const program = ts.createProgram(rootNames, { ...parsed.options, noEmit: true });
  const files: ts.SourceFile[] = [];
  const excluded = [...discovered.excluded];
  for (const filename of discovered.sources) {
    const source = program.getSourceFile(filename);
    if (!source) {
      const relative = path.relative(root, filename).split(path.sep).join('/');
      if (Object.hasOwn(APPLICATION_SOURCE_DIRECTORIES, relative.split('/')[0] ?? '')) {
        throw new Error(`Application source is excluded from the TypeScript program: ${relative}`);
      }
      excluded.push(relative);
      continue;
    }
    files.push(source);
  }
  const compilerErrors = ts.getPreEmitDiagnostics(program).filter(item => item.category === ts.DiagnosticCategory.Error).map(item => {
    const message = ts.flattenDiagnosticMessageText(item.messageText, '\n');
    if (!item.file || item.start === undefined) return `TS${item.code}: ${message}`;
    const position = item.file.getLineAndCharacterOfPosition(item.start);
    return `${path.relative(root, item.file.fileName)}:${position.line + 1}:${position.character + 1} TS${item.code}: ${message}`;
  });
  return { context: { root, files, program, checker: program.getTypeChecker(), policy }, excluded: [...new Set(excluded)].sort(), compilerErrors };
}

function recognizedNextConfig(text: string): boolean {
  const source = ts.createSourceFile('eslint.config.mjs', text, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  const imports = source.statements.filter(ts.isImportDeclaration);
  const allowed: Readonly<Record<string, true>> = { 'eslint/config': true, 'eslint-config-next/core-web-vitals': true, 'eslint-config-next/typescript': true };
  if (!imports.length || imports.some(item => !ts.isStringLiteral(item.moduleSpecifier) || !Object.hasOwn(allowed, item.moduleSpecifier.text))) return false;
  let valid = true;
  function inspect(node: ts.Node): void {
    if (ts.isCallExpression(node) && (!ts.isIdentifier(node.expression) || !['defineConfig', 'globalIgnores'].includes(node.expression.text))) valid = false;
    if (ts.isPropertyAssignment(node) && node.name.getText(source) !== 'ignores') valid = false;
    ts.forEachChild(node, inspect);
  }
  inspect(source);
  return valid && imports.some(item => ts.isStringLiteral(item.moduleSpecifier) && item.moduleSpecifier.text === 'eslint-config-next/core-web-vitals');
}

function nextConfigRegistersTypescriptPlugin(text: string): boolean {
  const source = ts.createSourceFile('eslint.config.mjs', text, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  return source.statements.some(statement => ts.isImportDeclaration(statement)
    && ts.isStringLiteral(statement.moduleSpecifier)
    && statement.moduleSpecifier.text === 'eslint-config-next/typescript');
}

export function initializeProject(rootInput: string): { root: string; changed: string[] } {
  const root = fs.realpathSync(path.resolve(rootInput));
  preflightDestinations(INITIALIZATION_TARGETS.map(file => path.join(root, file)));
  const facts = inspectProject(root);
  const existing = ESLINT_FILES.filter(file => fs.existsSync(path.join(root, file)));
  if (existing.length > 1) throw new Error('Multiple ESLint entry points: use the manual integration instructions');
  const currentName = existing[0];
  const current = currentName ? fs.readFileSync(path.join(root, currentName), 'utf8') : undefined;
  const generated = current === INTEGRATION || current?.includes('// Hexbound policy appended after the original Next.js template.');
  if (current !== undefined && !generated && !recognizedNextConfig(current)) throw new Error('Custom ESLint configuration will not be overwritten; use the documented manual integration');
  const policyPath = path.join(root, POLICY_FILE);
  if (fs.existsSync(policyPath)) loadPolicy(root);
  const tsPath = path.join(root, 'tsconfig.json'); const tsConfig = ts.readConfigFile(tsPath, ts.sys.readFile);
  if (tsConfig.error) throw new Error('Cannot initialize an invalid tsconfig.json');
  const configObject = z.object({ compilerOptions: z.record(z.string(), z.unknown()).optional(), include: z.array(z.string()).optional(), references: z.array(z.unknown()).optional() }).passthrough().parse(tsConfig.config);
  if (configObject.references?.length) throw new Error('tsconfig references are not supported');
  const options = { ...configObject.compilerOptions };
  for (const option of REQUIRED_COMPILER_OPTIONS) options[option] = true;
  for (const option of STRICT_OPTIONS) if (options[option] === false) options[option] = true;
  if (options['types'] === undefined) options['types'] = ['node'];
  const include = [...new Set([...(configObject.include ?? ['**/*.ts', '**/*.tsx']), '**/*.mts', '**/*.cts'])];
  const nextConfig = JSON.stringify({ ...configObject, compilerOptions: options, include }, null, 2) + '\n';
  let eslint = INTEGRATION;
  if (current && !generated) {
    const source = ts.createSourceFile('eslint.config.mjs', current, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
    const assignment = source.statements.find(ts.isExportAssignment);
    if (!assignment) throw new Error('Next template lacks an export default; integrate manually');
    const expression = assignment.expression.getText(source);
    const start = assignment.getStart(source); const end = assignment.getEnd();
    const reuseTypescriptEslint = nextConfigRegistersTypescriptPlugin(current);
    eslint = current.slice(0, start) + current.slice(end) + `\n// Hexbound policy appended after the original Next.js template.\nimport { createConfig as createHexboundConfig } from 'hexbound/eslint';\nexport default [...(${expression}), ...createHexboundConfig(import.meta.dirname, { reuseTypescriptEslint: ${reuseTypescriptEslint} })];\n`;
  } else if (current) eslint = current;
  const { scripts: oldScripts = {}, ...manifestFields } = facts.manifest;
  if (oldScripts['check:hexbound'] && oldScripts['check:hexbound'] !== 'hexbound check') throw new Error('Existing check:hexbound script has custom behavior; integrate manually');
  if (oldScripts['check:hexbound:full'] && oldScripts['check:hexbound:full'] !== 'hexbound check && next build') throw new Error('Existing check:hexbound:full script has custom behavior; integrate manually');
  const scripts = { ...oldScripts, 'check:hexbound': 'hexbound check', 'check:hexbound:full': 'hexbound check && next build' };
  const manifest = { ...manifestFields, scripts };
  const pending = new Map<string, string>([
    [tsPath, nextConfig], [path.join(root, currentName ?? 'eslint.config.mjs'), eslint],
    [path.join(root, 'package.json'), JSON.stringify(manifest, null, 2) + '\n'],
  ]);
  if (!fs.existsSync(policyPath)) pending.set(policyPath, JSON.stringify(defaultPolicy, null, 2) + '\n');
  const instructionsPath = path.join(root, 'AGENTS.md');
  const instruction = '\n## Hexbound\n\nUse the hexbound skill for TypeScript/Next.js changes. Follow HB001–HB020; run `hexbound check` before completion. Never weaken checks or self-approve exceptions.\n';
  const before = fs.existsSync(instructionsPath) ? fs.readFileSync(instructionsPath, 'utf8') : '';
  if (!before.includes('## Hexbound')) pending.set(instructionsPath, before + instruction);
  preflightDestinations(pending.keys());
  const changed: string[] = [];
  for (const [filename, content] of pending) {
    if (!fs.existsSync(filename) || fs.readFileSync(filename, 'utf8') !== content) { fs.writeFileSync(filename, content); changed.push(path.relative(root, filename)); }
  }
  return { root, changed };
}
